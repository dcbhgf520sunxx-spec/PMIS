const { readFile } = require('node:fs/promises')
const { existsSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { createHash } = require('node:crypto')
const packagedRoot = resolve(__dirname, '../../ontology/standard')
const sourceRoot = existsSync(packagedRoot) ? packagedRoot : resolve(__dirname, '../../../artifacts/sidm-ontology/standard')
const hash = value => createHash('sha256').update(value).digest('hex')
// Generated display metadata, not a replacement ontology. OWL and SHACL remain authoritative.
async function readOntologyModel(root = sourceRoot) {
  try {
    const [view, owl, shapes] = await Promise.all([
      readFile(join(root, 'model-view-data.cjs'), 'utf8'), readFile(join(root, 'sidm.ttl')), readFile(join(root, 'shapes.ttl'))
    ])
    const prefix = '// Generated by render-model.py; do not edit.\nmodule.exports = '
    if (!view.startsWith(prefix)) throw new Error('本体展示文件格式不正确')
    const model = JSON.parse(view.slice(prefix.length).trim().replace(/;$/, ''))
    if (model.sha256 !== hash(owl) || model.shapesSha256 !== hash(shapes)) throw new Error('本体定义已更新，请重新生成展示文件')
    const business = resolve(root, '../../../docs/SIDM业务骨架.md')
    if (existsSync(business) && model.businessSha256 !== hash(await readFile(business))) throw new Error('业务骨架已更新，请重新生成展示文件')
    if (!Array.isArray(model.classes) || !Array.isArray(model.relations)) throw new Error('本体展示文件内容不完整')
    return model
  } catch (error) {
    const unavailable = new Error(error.code === 'ENOENT' ? '本体展示文件缺失，请生成后重试' : error.message)
    unavailable.status = 503
    throw unavailable
  }
}
module.exports = { readOntologyModel }
